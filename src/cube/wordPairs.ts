export function getMnemonicWord(pair: string): string | null {
  const upper = pair.toUpperCase().trim();
  if (DEFAULT_WORD_PAIRS[upper]) {
    return DEFAULT_WORD_PAIRS[upper];
  }

  // Fallback phonetic for single leftover target letters
  if (upper.length === 1) {
    const singleLetterWords: Record<string, string> = {
      A: 'Apple',
      B: 'Bat',
      C: 'Cat',
      D: 'Dog',
      E: 'Egg',
      F: 'Fish',
      G: 'Goat',
      H: 'Hat',
      I: 'Ice',
      J: 'Jam',
      K: 'Kite',
      L: 'Lion',
      M: 'Moon',
      N: 'Nut',
      O: 'Owl',
      P: 'Pen',
      Q: 'Queen',
      R: 'Ring',
      S: 'Sun',
      T: 'Top',
      U: 'Umbrella',
      V: 'Van',
      W: 'Web',
      X: 'X-Ray',
    };
    return singleLetterWords[upper] || null;
  }

  return null;
}
